#!/usr/bin/env node
/** Real DOM/form contract checks without a product route, database or provider. */
import assert from "node:assert/strict";
import http from "node:http";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import postcss from "postcss";
import tailwind from "tailwindcss";
import loadConfig from "tailwindcss/loadConfig.js";
import { chromium } from "playwright";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const temporary = await fs.mkdtemp(path.join(os.tmpdir(), "bc-dd-select-"));
let browser;
let server;
try {
  await build({ entryPoints: [path.join(root, "scripts/select-fixture.tsx")], outfile: path.join(temporary, "fixture.js"), bundle: true, jsx: "automatic", define: { "process.env.NODE_ENV": '"production"' } });
  const config = loadConfig(path.join(root, "tailwind.config.ts"));
  const css = await postcss([tailwind({ ...config, content: [path.join(root, "src/**/*.{ts,tsx}"), path.join(root, "scripts/select-fixture.tsx")] })]).process(await fs.readFile(path.join(root, "src/app/globals.css"), "utf8"), { from: undefined });
  server = http.createServer(async (request, response) => {
    if (request.url === "/fixture.js") { response.setHeader("content-type", "text/javascript"); response.end(await fs.readFile(path.join(temporary, "fixture.js"))); }
    else if (request.url === "/style.css") { response.setHeader("content-type", "text/css"); response.end(css.css); }
    else { response.setHeader("content-type", "text/html"); response.end('<!doctype html><html lang="en" data-theme="light"><head><meta name="viewport" content="width=device-width, initial-scale=1"><title>Select fixture</title><link rel="stylesheet" href="/style.css"></head><body><div id="root"></div><script src="/fixture.js"></script></body></html>'); }
  });
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 800, height: 900 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  const required = page.getByRole("combobox", { name: "Required choice", exact: true });
  const defaultChoice = page.getByRole("combobox", { name: "Default choice", exact: true });
  const choose = async (control, label) => { await control.click(); await page.getByRole("option", { name: label, exact: true }).click(); };
  const entries = async () => JSON.parse(await page.locator("#entries").textContent());
  const changeCount = async () => Number(await page.locator("#changes").textContent());
  await required.waitFor();
  assert.equal(await defaultChoice.textContent(), "Beta");
  assert.equal(await changeCount(), 0, "Initial values must not mark a form dirty");
  assert(await page.getByRole("combobox", { name: "Disabled choice", exact: true }).isDisabled());
  assert(await page.getByRole("combobox", { name: "Fieldset choice", exact: true }).isDisabled());
  await page.getByRole("button", { name: "Submit choices", exact: true }).click();
  assert.deepEqual(await entries(), [], "Required empty choice must prevent submission");
  assert.equal(await required.getAttribute("aria-invalid"), "true");
  assert(await required.evaluate((element) => document.activeElement === element), "Validation focuses custom trigger");
  assert.match(await required.getAttribute("aria-describedby"), /hint.*validation/);
  await page.getByRole("button", { name: "Cancel resets: false" }).click();
  await page.getByRole("button", { name: "Reset choices", exact: true }).click();
  assert.equal(await required.getAttribute("aria-invalid"), "true", "Cancelled reset preserves validation");
  await page.getByRole("button", { name: "Cancel resets: true" }).click();
  await page.getByText("Required choice", { exact: true }).click();
  await page.keyboard.press("ArrowDown");
  await page.getByRole("listbox").waitFor();
  assert.equal(await page.getByRole("option", { name: "Blocked", exact: true }).getAttribute("aria-disabled"), "true");
  assert.equal(await page.getByRole("option", { name: "Group disabled", exact: true }).getAttribute("aria-disabled"), "true");
  await page.keyboard.press("End");
  await page.waitForFunction(() => document.activeElement?.textContent === "Delta");
  await page.keyboard.press("Enter");
  assert.equal(await required.textContent(), "Delta", "Keyboard skips disabled group");
  assert.equal(await page.locator("#native-event").textContent(), "true");
  assert.equal(await changeCount(), 1, "One selection emits one named form change");
  await required.focus();
  await page.keyboard.press("b");
  assert.equal(await required.textContent(), "Beta", "Closed control supports typeahead");
  await required.click();
  await page.keyboard.press("Escape");
  await page.waitForFunction((id) => document.activeElement?.id === id, await required.getAttribute("id"));
  assert(await required.evaluate((element) => document.activeElement === element));
  assert.equal(await page.getByRole("listbox").count(), 0);
  await required.click();
  // Locator actionability waits for the open menu to settle before the outside interaction.
  await page.locator("html").click({ position: { x: 4, y: 4 } });
  await page.getByRole("listbox").waitFor({ state: "detached" });
  assert.equal(await page.getByRole("listbox").count(), 0, "Outside click dismisses menu");
  await choose(defaultChoice, "Alpha");
  await choose(page.getByRole("combobox", { name: "External choice", exact: true }), "Beta");
  await page.getByRole("button", { name: "Submit choices", exact: true }).click();
  assert.deepEqual(await entries(), [["required", "beta"], ["default", "alpha"], ["optional", ""], ["external", "beta"]], "FormData preserves real values once and excludes disabled controls");
  const beforeReset = await changeCount();
  await page.getByRole("button", { name: "Reset choices", exact: true }).click();
  await page.waitForFunction((id) => document.getElementById(id)?.textContent === "Beta", await defaultChoice.getAttribute("id"));
  assert.equal(await required.textContent(), "Beta", "Controlled value remains owned by caller");
  assert.equal(await defaultChoice.textContent(), "Beta", "Reset restores defaultValue");
  assert.equal(await page.getByRole("combobox", { name: "External choice", exact: true }).textContent(), "Alpha");
  assert.equal(await changeCount(), beforeReset, "Reset must not emit synthetic changes");
  await page.getByRole("button", { name: "Reset controlled value: false" }).click();
  await page.getByRole("button", { name: "Reset choices", exact: true }).click();
  await page.waitForFunction(() => document.querySelector('select[name="required"]').value === "alpha");
  assert.equal(await required.textContent(), "Alpha", "Caller can reset a controlled value");
  await choose(required, "Delta");
  assert.equal(await required.textContent(), "Delta", "Controlled reset must not block subsequent selection");
  assert.equal(await page.locator('select[name="required"]').inputValue(), "delta");
  await page.getByRole("button", { name: "Remove Beta option", exact: true }).click();
  assert.equal(await defaultChoice.textContent(), "None", "Removed option falls back to first available");
  await choose(required, "Choose an option");
  const beforeProgrammatic = await changeCount();
  await page.getByRole("button", { name: "Set controlled value", exact: true }).click();
  assert.equal(await required.textContent(), "Beta");
  assert.equal(await changeCount(), beforeProgrammatic, "Controlled updates must not mark form dirty");
  await page.getByRole("button", { name: "Focus native ref", exact: true }).click();
  assert(await required.evaluate((element) => document.activeElement === element));
  await choose(page.getByRole("combobox", { name: "Header appearance", exact: true }), "Dark");
  assert.equal(await page.getByRole("combobox", { name: "Settings appearance", exact: true }).textContent(), "Dark");
  await choose(page.getByRole("combobox", { name: "Settings appearance", exact: true }), "System");
  await page.emulateMedia({ colorScheme: "light" });
  await page.waitForFunction(() => document.documentElement.dataset.theme === "light");
  await page.emulateMedia({ colorScheme: "dark" });
  await page.waitForFunction(() => document.documentElement.dataset.theme === "dark");
  await page.setViewportSize({ width: 360, height: 400 });
  await page.getByRole("button", { name: "Open edge dialog", exact: true }).click();
  const longChoice = page.getByRole("combobox", { name: "Long choice", exact: true });
  await longChoice.click();
  const menu = page.getByRole("listbox");
  await menu.waitFor();
  const bounds = await menu.boundingBox();
  assert(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 360 && bounds.y + bounds.height <= 400, "Menu stays inside short narrow viewport");
  await page.keyboard.press("End");
  const last = page.getByRole("option", { name: /Option 40 with/ });
  await page.waitForFunction(() => document.activeElement?.textContent?.startsWith("Option 40 with"));
  assert(await last.evaluate((element) => { const box = element.getBoundingClientRect(); return box.top >= 0 && box.bottom <= innerHeight; }), "Last long option scrolls into view");
  await page.keyboard.press("Enter");
  assert.match(await longChoice.textContent(), /Option 40/);
  await page.keyboard.press("Escape");
  assert.equal(await page.getByRole("dialog").count(), 0);
  assert.deepEqual(errors, [], "No runtime errors");
  console.log("PASS: custom select submission, native events, empty/required/default/controlled values, reset, disabled groups, external form, keyboard, focus, collision/scroll in a dialog, and theme synchronization.");
} finally {
  await browser?.close();
  await new Promise((resolve) => server ? server.close(resolve) : resolve());
  await fs.rm(temporary, { recursive: true, force: true });
}
